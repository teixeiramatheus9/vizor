// CJS on purpose: Electron preload scripts require CommonJS in sandboxed renderers.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('manager', {
  togglePanel: () => ipcRenderer.send('overlay:toggle-panel'),
  activateBubble: () => ipcRenderer.send('bubble:activate'),
  tooltipClick: (sessionId) => ipcRenderer.send('tooltip:click', sessionId ?? null),
  openPanel: () => ipcRenderer.send('overlay:open-panel'),
  closeOverlay: () => ipcRenderer.send('overlay:close'),
  openSettings: () => ipcRenderer.send('settings:open'),
  closeSettings: () => ipcRenderer.send('settings:close'),
  quit: () => ipcRenderer.send('app:quit'),
  panelOpened: () => ipcRenderer.send('panel:opened'),
  removeSession: (sessionId) => ipcRenderer.send('session:remove', sessionId),
  rescanSessions: () => ipcRenderer.invoke('sessions:rescan'),
  applyUpdate: () => ipcRenderer.send('update:apply'),
  checkUpdates: () => ipcRenderer.invoke('update:check'),
  dismissHint: () => ipcRenderer.send('hint:dismiss'),
  onHalo: (fn) => ipcRenderer.on('halo', (_event, payload) => fn(payload)),
  renameSession: (sessionId, alias) => ipcRenderer.send('session:rename', { sessionId, alias }),
  bridgeStatus: () => ipcRenderer.invoke('bridge:status'),
  bridgeInstall: () => ipcRenderer.invoke('bridge:install'),
  bridgeUninstall: () => ipcRenderer.invoke('bridge:uninstall'),
  dragStart: () => ipcRenderer.send('drag:start'),
  dragEnd: () => ipcRenderer.send('drag:end'),
  focusSession: (sessionId) => ipcRenderer.invoke('warp:focus', sessionId),
  sendReply: (sessionId, text) => ipcRenderer.invoke('warp:reply', { sessionId, text }),
  readConversation: (sessionId) => ipcRenderer.invoke('transcript:tail', sessionId),
  answerQuestion: (sessionId, optionIndex) =>
    ipcRenderer.invoke('warp:answer', { sessionId, optionIndex }),
  chatWithManager: (text) => ipcRenderer.invoke('manager:chat', text),
  answerGuard: (id, choice) => ipcRenderer.invoke('guard:answer', { id, choice }),
  openRules: () => ipcRenderer.send('rules:open'),
  voiceVocabulary: () => ipcRenderer.invoke('voice:vocabulary'),
  voiceUnlearn: (heard) => ipcRenderer.invoke('voice:unlearn', heard),
  voiceRescan: () => ipcRenderer.invoke('voice:rescan'),
  setGuardEnabled: (enabled) => ipcRenderer.invoke('rules:set-enabled', enabled),
  getInboundPolicy: () => ipcRenderer.invoke('inbound:get'),
  setInboundPolicy: (value) => ipcRenderer.invoke('inbound:set', value),
  limitsSettings: () => ipcRenderer.invoke('limits:settings'),
  limitsReconnect: () => ipcRenderer.invoke('limits:reconnect'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (partial) => ipcRenderer.invoke('config:set', partial),
  onState: (callback) => ipcRenderer.on('state', (_event, state) => callback(state)),
  onTooltip: (callback) => ipcRenderer.on('tooltip', (_event, data) => callback(data)),
  onChime: (callback) => ipcRenderer.on('chime', (_event, data) => callback(data)),
  speak: (text, volume) => ipcRenderer.send('tts:speak', { text, volume }),
  onBlur: (callback) => ipcRenderer.on('ui:blur', () => callback()),
  onEnv: (callback) => ipcRenderer.on('ui:env', (_event, env) => callback(env)),
  onOverlayMode: (callback) => ipcRenderer.on('overlay:mode', (_event, mode) => callback(mode)),
  onClick: (callback) => ipcRenderer.on('ui:click', () => callback()),
  onSpotted: (callback) => ipcRenderer.on('ui:spotted', () => callback()),
  onOpenChat: (callback) => ipcRenderer.on('ui:open-chat', () => callback()),
});
