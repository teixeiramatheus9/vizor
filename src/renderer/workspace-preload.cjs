// CJS on purpose: Electron preload scripts require CommonJS.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('vizor', {
  onState: (callback) => ipcRenderer.on('workspace:state', (_event, state) => callback(state)),
  addProject: () => ipcRenderer.invoke('workspace:add-project'),
  openActionMenu: (rect) => ipcRenderer.send('workspace:action-menu', rect),
  removeProject: (root) => ipcRenderer.send('workspace:remove-project', root),
  openTerminal: (cwd, kind, sessionId = null) => ipcRenderer.invoke('pty:open', { cwd, kind, sessionId }),
  listConversations: (cwd) => ipcRenderer.invoke('workspace:conversations', cwd),
  outsideStatus: (sessionId) => ipcRenderer.invoke('workspace:outside-status', sessionId),
  bringToVizor: (sessionId) => ipcRenderer.invoke('workspace:bring', sessionId),
  reportActiveTab: (id) => ipcRenderer.send('workspace:active-tab', id ?? null),
  answerGuard: (id, choice) => ipcRenderer.invoke('guard:answer', { id, choice }),
  onVoice: (callback) => ipcRenderer.on('workspace:voice', (_event, payload) => callback(payload)),
  writeTerminal: (id, data) => ipcRenderer.send('pty:write', { id, data }),
  resizeTerminal: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  closeTerminal: (id) => ipcRenderer.send('pty:close', id),
  ackTerminal: (id, chars) => ipcRenderer.send('pty:ack', { id, chars }),
  setTerminalTitle: (id, title) => ipcRenderer.send('pty:title', { id, title }),
  terminalBuffer: (id) => ipcRenderer.invoke('pty:buffer', id),
  onTerminalData: (callback) => ipcRenderer.on('pty:data', (_event, payload) => callback(payload)),
  onTerminalExit: (callback) => ipcRenderer.on('pty:exit', (_event, payload) => callback(payload)),
  focusOutside: (sessionId) => ipcRenderer.invoke('warp:focus', sessionId),
  getTaskEdits: (sessionId, taskId) => ipcRenderer.invoke('edits:task', { sessionId, taskId }),
  getFileView: (sessionId, taskId, filePath) => ipcRenderer.invoke('edits:file', { sessionId, taskId, filePath }),
  getPrefs: () => ipcRenderer.invoke('workspace:prefs', {}),
  setPrefs: (set) => ipcRenderer.invoke('workspace:prefs', { set }),
  addComment: (sessionId, editId, text) => ipcRenderer.invoke('comments:add', { sessionId, editId, text }),
  copyComment: (sessionId, commentId) => ipcRenderer.invoke('comments:copy', { sessionId, commentId }),
  onFocusSession: (callback) => ipcRenderer.on('workspace:focus', (_event, payload) => callback(payload)),
  reportSelection: (sessionId) => ipcRenderer.send('workspace:selected', sessionId ?? null),
  onEditsChanged: (callback) => ipcRenderer.on('edits:changed', (_event, payload) => callback(payload)),
  // The Maestro (#159).
  onMaestroSay: (callback) => ipcRenderer.on('maestro:say', (_event, payload) => callback(payload)),
  onMaestroNarration: (callback) => ipcRenderer.on('maestro:narration', (_event, payload) => callback(payload)),
  onMaestroOrder: (callback) => ipcRenderer.on('maestro:order', (_event, payload) => callback(payload)),
  setMaestro: (on) => ipcRenderer.send('maestro:set', Boolean(on)),
  focusMusician: (sessionId) => ipcRenderer.send('maestro:focus', sessionId),
  onMaestroGraph: (callback) => ipcRenderer.on('maestro:graph', (_event, payload) => callback(payload)),
  maestroGraph: (root) => ipcRenderer.invoke('maestro:graph', root),
});
